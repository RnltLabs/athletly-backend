def _make_profile(
    *,
    max_session_minutes: int = 90,
    training_days_per_week: int = 5,
    sports: list[str] | None = None,
    available_sports: list[str] | None = None,
    tier: str | None = None,
) -> dict:
    sports = sports or ["running"]
    return {
        "name": "Test",
        "sports": sports,
        "tier": tier,
        "goal": {"event": "Berlin Marathon", "target_date": "2026-09-27"},
        "fitness": {"estimated_vo2max": 55, "threshold_pace_min_km": 4.0},
        "constraints": {
            "max_session_minutes": max_session_minutes,
            "training_days_per_week": training_days_per_week,
            "available_sports": available_sports or sports,
        },
    }


def _next_monday() -> date:
    today = date.today()
    delta = (7 - today.weekday()) % 7
    return today + timedelta(days=delta or 7)


def _make_outline_payload(
    *,
    duration_weeks: int = 4,
    start_date: str | None = None,
    training_days_per_week: int = 5,
) -> dict:
    """Build a valid planner JSON payload for `duration_weeks` weeks."""
    start_date = start_date or _next_monday().isoformat()
    weekdays = ["monday", "tuesday", "wednesday", "thursday",
                "friday", "saturday", "sunday"]
    template_values = ["easy", "quality", "easy", "long", "rest",
                       "long_or_quality", "rest"]
    # Adjust template so non-rest count matches training_days_per_week.
    template_values = ["rest"] * 7
    pick = ["tuesday", "thursday", "saturday", "monday", "wednesday",
            "sunday", "friday"]
    for d in pick[:training_days_per_week]:
        template_values[weekdays.index(d)] = (
            "quality" if d == "tuesday"
            else "long" if d == "saturday"
            else "easy"
        )
    template = dict(zip(weekdays, template_values))

    return {
        "outline": {
            "duration_weeks": duration_weeks,
            "start_date": start_date,
            "goal_event": "Berlin Marathon",
            "goal_date": "2026-09-27",
            "phases": [
                {
                    "weeks": list(range(1, duration_weeks + 1)),
                    "phase": "Base",
                    "weekly_volume_km": 50,
                    "intensity_distribution": "80/20",
                    "focus": "aerobic foundation",
                }
            ],
            "weekly_template": template,
        },
        "constraints_acknowledged": {
            "max_session_minutes": 90,
            "training_days_per_week": training_days_per_week,
            "available_sports": ["running"],
        },
    }


def _make_executor_sessions(
    *,
    week_start: date,
    template: dict[str, str],
) -> dict:
    """Build a valid executor response for one week."""
    weekdays = ["monday", "tuesday", "wednesday", "thursday",
                "friday", "saturday", "sunday"]
    sessions = []
    for idx, day in enumerate(weekdays):
        slot = template[day]
        if slot == "rest":
            continue
        sessions.append({
            "day": day,
            "date": (week_start + timedelta(days=idx)).isoformat(),
            "sport": "running",
            "name": f"{slot.title()} run",
            "description": "Generated by test",
            "duration_minutes": 45 if slot == "easy" else 60,
            "intensity": "low" if slot == "easy" else "moderate",
        })
    return {"sessions": sessions}


def _mock_completion(content: str) -> MagicMock:
    """Build a chat_completion-shaped MagicMock returning `content`."""
    msg = SimpleNamespace(content=content)
    choice = SimpleNamespace(message=msg)
    resp = SimpleNamespace(choices=[choice])
    return resp


