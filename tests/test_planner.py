class TestSavePlanIntegration:
    """Verify the heuristic plumbing inside save_plan without hitting LLMs."""

    def _make_user_model(self, *, tier: str = "free"):
        um = MagicMock()
        um.user_id = "test-uid"
        um.project_profile.return_value = _make_profile(tier=tier)
        return um

    def _register(self, user_model):
        from src.agent.tools.registry import ToolRegistry
        registry = ToolRegistry()
        # Disable supabase persistence: use the file-backed fallback path
        # so we do not touch the DB during unit tests.
        with patch("src.agent.tools.planning_tools.get_settings") as mock_get:
            settings = MagicMock()
            settings.use_supabase = False
            settings.agenticsports_user_id = "test-uid"
            mock_get.return_value = settings
            from src.agent.tools.planning_tools import register_planning_tools
            register_planning_tools(registry, user_model)
        return registry

    def test_free_tier_long_plan_clamped(self, tmp_path, monkeypatch):
        """Free-tier user passing 12 weeks gets clamped to 1 week, NO planner."""
        monkeypatch.chdir(tmp_path)
        user_model = self._make_user_model(tier="free")
        registry = self._register(user_model)
        save_tool = registry._tools["save_plan"]

        with patch("src.agent.planner.generate_training_plan") as mock_gen:
            result = save_tool.handler(plan={
                "duration_weeks": 12,
                "start_date": _next_monday().isoformat(),
                "sessions": [],
            })
            mock_gen.assert_not_called()

        assert result["saved"] is True

    def test_pro_tier_short_plan_skips_planner(self, tmp_path, monkeypatch):
        """Pro tier but session_count<14: planner is NOT invoked."""
        monkeypatch.chdir(tmp_path)
        user_model = self._make_user_model(tier="pro")
        registry = self._register(user_model)
        save_tool = registry._tools["save_plan"]

        with patch("src.agent.planner.generate_training_plan") as mock_gen:
            result = save_tool.handler(plan={
                "duration_weeks": 2,
                "start_date": _next_monday().isoformat(),
                "sessions": [{
                    "day": "monday",
                    "date": _next_monday().isoformat(),
                    "sport": "running",
                    "name": "Easy",
                    "duration_minutes": 45,
                    "intensity": "low",
                }],
            })
            mock_gen.assert_not_called()

        assert result["saved"] is True

    def test_pro_tier_long_plan_triggers_planner(self, tmp_path, monkeypatch):
        """Pro tier, duration_weeks=12: planner IS invoked."""
        monkeypatch.chdir(tmp_path)
        user_model = self._make_user_model(tier="pro")
        registry = self._register(user_model)
        save_tool = registry._tools["save_plan"]

        outline_payload = _make_outline_payload(duration_weeks=3)
        sd = date.fromisoformat(outline_payload["outline"]["start_date"])
        sessions = []
        for wk in range(3):
            week_start = sd + timedelta(days=wk * 7)
            sessions.extend(
                _make_executor_sessions(
                    week_start=week_start,
                    template=outline_payload["outline"]["weekly_template"],
                )["sessions"]
            )
        fake_result = PlannerResult(
            plan={
                "start_date": outline_payload["outline"]["start_date"],
                "focus": "test plan",
                "sessions": sessions,
            },
            mode="plan_and_execute",
            meta={"weeks": 3},
        )

        with patch(
            "src.agent.planner.generate_training_plan",
            return_value=fake_result,
        ) as mock_gen:
            result = save_tool.handler(plan={"duration_weeks": 12})

            mock_gen.assert_called_once()
            args, kwargs = mock_gen.call_args
            assert kwargs["request"]["duration_weeks"] == 12

        assert result["saved"] is True
