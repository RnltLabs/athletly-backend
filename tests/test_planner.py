class TestEndToEnd:
    def test_happy_path(self):
        """Full Plan-and-Execute run with mocked planner+executor."""
        profile = _make_profile()
        request = {"duration_weeks": 3, "goal_event": "Berlin Marathon"}
        outline_payload = _make_outline_payload(duration_weeks=3)
        outline = outline_payload["outline"]

        def fake_completion(messages, system_prompt=None, **kwargs):
            # First call uses planner_system.md. Subsequent calls use
            # the executor_system.md. We disambiguate by inspecting the
            # system prompt header.
            if system_prompt and "PLANNER" in system_prompt:
                return _mock_completion(json.dumps(outline_payload))
            # Executor: parse week_index from the user message JSON block.
            user_content = messages[0]["content"]
            week_slot = json.loads(
                user_content.split("```json", 1)[1].split("```", 1)[0]
            )
            week_start = date.fromisoformat(week_slot["week_start_date"])
            return _mock_completion(
                json.dumps(
                    _make_executor_sessions(
                        week_start=week_start,
                        template=week_slot["weekday_template"],
                    )
                )
            )

        with patch.object(planner_mod, "chat_completion", side_effect=fake_completion):
            result = generate_training_plan(request=request, profile=profile)

        assert result.mode == "plan_and_execute"
        plan = result.plan
        assert plan["start_date"] == outline["start_date"]
        assert plan["focus"]
        expected_count = 3 * profile["constraints"]["training_days_per_week"]
        assert len(plan["sessions"]) == expected_count
        # Every session inside the date range.
        sd = date.fromisoformat(plan["start_date"])
        for s in plan["sessions"]:
            d = date.fromisoformat(s["date"])
            assert sd <= d < sd + timedelta(days=3 * 7)
            assert s["duration_minutes"] <= 90
            assert s["sport"] == "running"

    def test_planner_json_parse_failure_falls_back(self):
        profile = _make_profile()
        request = {"duration_weeks": 4}

        def bad_planner(messages, system_prompt=None, **kwargs):
            return _mock_completion("not json at all {{{")

        with patch.object(planner_mod, "chat_completion", side_effect=bad_planner):
            result = generate_training_plan(request=request, profile=profile)

        assert result.mode == "inline_fallback"
        assert "fallback_reason" in result.meta
        # Original request preserved.
        assert result.plan["duration_weeks"] == 4

    def test_executor_invalid_returns_fallback(self):
        profile = _make_profile()
        request = {"duration_weeks": 3}
        outline_payload = _make_outline_payload(duration_weeks=3)

        def fake_completion(messages, system_prompt=None, **kwargs):
            if system_prompt and "PLANNER" in system_prompt:
                return _mock_completion(json.dumps(outline_payload))
            # Always return invalid executor output.
            return _mock_completion('{"sessions": []}')

        with patch.object(planner_mod, "chat_completion", side_effect=fake_completion):
            result = generate_training_plan(request=request, profile=profile)

        assert result.mode == "inline_fallback"
        assert "executor" in result.meta.get("fallback_reason", "")


