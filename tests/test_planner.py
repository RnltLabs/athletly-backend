class TestComplexityHeuristic:
    """`should_use_plan_and_execute` threshold and tier gating."""

    def test_free_tier_never_triggers(self):
        request = {"duration_weeks": 16}
        profile = _make_profile(training_days_per_week=6)
        assert should_use_plan_and_execute(request, profile, "free") is False

    def test_pro_short_plan_does_not_trigger(self):
        # 2 weeks * 5 days = 10 sessions, under threshold 14.
        request = {"duration_weeks": 2}
        profile = _make_profile(training_days_per_week=5)
        assert should_use_plan_and_execute(request, profile, "pro") is False

    def test_pro_at_threshold_triggers(self):
        # 3 weeks * 5 days = 15 sessions >= 14.
        request = {"duration_weeks": 3}
        profile = _make_profile(training_days_per_week=5)
        assert should_use_plan_and_execute(request, profile, "pro") is True

    def test_pro_just_below_threshold(self):
        # 2 weeks * 6 days = 12 sessions < 14.
        request = {"duration_weeks": 2}
        profile = _make_profile(training_days_per_week=6)
        assert should_use_plan_and_execute(request, profile, "pro") is False

    def test_pro_just_above_threshold(self):
        # 2 weeks * 7 days = 14, exactly threshold.
        request = {"duration_weeks": 2}
        profile = _make_profile(training_days_per_week=7)
        assert should_use_plan_and_execute(request, profile, "pro") is True

    def test_missing_duration_returns_false(self):
        request: dict = {}
        profile = _make_profile()
        assert should_use_plan_and_execute(request, profile, "pro") is False

    def test_long_plan_capped_at_max(self):
        # 100 weeks should be capped to _MAX_PLAN_WEEKS but heuristic
        # still triggers (capped value is plenty above threshold).
        request = {"duration_weeks": 100}
        profile = _make_profile()
        assert should_use_plan_and_execute(request, profile, "pro") is True


