class TestExecutorSanitization:
    def test_clean_sessions_pass(self):
        outline = _make_outline_payload(duration_weeks=2)["outline"]
        profile = _make_profile()
        slot = planner_mod._build_week_slot(outline, 1, profile)
        week_start = date.fromisoformat(slot["week_start_date"])
        payload = _make_executor_sessions(
            week_start=week_start, template=slot["weekday_template"],
        )
        sanitized, err = planner_mod._sanitize_executor_sessions(
            payload["sessions"], slot, profile,
        )
        assert err is None
        # Should equal the number of non-rest days.
        expected = sum(
            1 for v in slot["weekday_template"].values() if v != "rest"
        )
        assert len(sanitized) == expected

    def test_duration_over_cap_rejected(self):
        outline = _make_outline_payload(duration_weeks=2)["outline"]
        profile = _make_profile(max_session_minutes=60)
        slot = planner_mod._build_week_slot(outline, 1, profile)
        week_start = date.fromisoformat(slot["week_start_date"])
        payload = _make_executor_sessions(
            week_start=week_start, template=slot["weekday_template"],
        )
        # Boost first session over the cap.
        payload["sessions"][0]["duration_minutes"] = 200
        _, err = planner_mod._sanitize_executor_sessions(
            payload["sessions"], slot, profile,
        )
        assert err is not None and "exceeds" in err

    def test_missing_day_rejected(self):
        outline = _make_outline_payload(duration_weeks=2)["outline"]
        profile = _make_profile()
        slot = planner_mod._build_week_slot(outline, 1, profile)
        week_start = date.fromisoformat(slot["week_start_date"])
        payload = _make_executor_sessions(
            week_start=week_start, template=slot["weekday_template"],
        )
        # Drop the first session.
        payload["sessions"] = payload["sessions"][1:]
        _, err = planner_mod._sanitize_executor_sessions(
            payload["sessions"], slot, profile,
        )
        assert err is not None and "missing" in err

    def test_rest_day_session_silently_dropped(self):
        outline = _make_outline_payload(duration_weeks=2)["outline"]
        profile = _make_profile()
        slot = planner_mod._build_week_slot(outline, 1, profile)
        week_start = date.fromisoformat(slot["week_start_date"])
        payload = _make_executor_sessions(
            week_start=week_start, template=slot["weekday_template"],
        )
        # Inject a session for a rest day.
        rest_day = next(
            d for d, v in slot["weekday_template"].items() if v == "rest"
        )
        rest_offset = planner_mod._WEEKDAY_TO_OFFSET[rest_day]
        payload["sessions"].append({
            "day": rest_day,
            "date": (week_start + timedelta(days=rest_offset)).isoformat(),
            "sport": "running",
            "name": "Extra",
            "duration_minutes": 30,
            "intensity": "low",
        })
        sanitized, err = planner_mod._sanitize_executor_sessions(
            payload["sessions"], slot, profile,
        )
        assert err is None
        assert all(s["day"] != rest_day for s in sanitized)

    def test_invalid_sport_replaced_with_available(self):
        outline = _make_outline_payload(duration_weeks=2)["outline"]
        profile = _make_profile(available_sports=["running"])
        slot = planner_mod._build_week_slot(outline, 1, profile)
        week_start = date.fromisoformat(slot["week_start_date"])
        payload = _make_executor_sessions(
            week_start=week_start, template=slot["weekday_template"],
        )
        payload["sessions"][0]["sport"] = "kayaking"
        sanitized, err = planner_mod._sanitize_executor_sessions(
            payload["sessions"], slot, profile,
        )
        assert err is None
        assert sanitized[0]["sport"] == "running"


