class TestConstraintValidation:
    def test_valid_plan_no_errors(self):
        profile = _make_profile()
        outline_payload = _make_outline_payload(duration_weeks=2)
        outline = outline_payload["outline"]
        # Build sessions matching the outline.
        sd = date.fromisoformat(outline["start_date"])
        all_sessions = []
        for wk in range(2):
            week_start = sd + timedelta(days=wk * 7)
            all_sessions.extend(
                _make_executor_sessions(
                    week_start=week_start,
                    template=outline["weekly_template"],
                )["sessions"]
            )
        plan = {
            "start_date": outline["start_date"],
            "sessions": all_sessions,
        }
        errors = planner_mod._validate_against_constraints(plan, profile, outline)
        assert errors == []

    def test_session_over_cap_flagged(self):
        profile = _make_profile(max_session_minutes=60)
        outline = _make_outline_payload(duration_weeks=1)["outline"]
        sd = date.fromisoformat(outline["start_date"])
        sessions = _make_executor_sessions(
            week_start=sd, template=outline["weekly_template"],
        )["sessions"]
        sessions[0]["duration_minutes"] = 200
        plan = {"start_date": outline["start_date"], "sessions": sessions}
        errors = planner_mod._validate_against_constraints(plan, profile, outline)
        assert any("exceeds" in e for e in errors)

    def test_wrong_session_count_per_week_flagged(self):
        profile = _make_profile(training_days_per_week=5)
        outline = _make_outline_payload(
            duration_weeks=1, training_days_per_week=5,
        )["outline"]
        sd = date.fromisoformat(outline["start_date"])
        sessions = _make_executor_sessions(
            week_start=sd, template=outline["weekly_template"],
        )["sessions"]
        # Drop one.
        sessions = sessions[:-1]
        plan = {"start_date": outline["start_date"], "sessions": sessions}
        errors = planner_mod._validate_against_constraints(plan, profile, outline)
        assert any("week 1" in e and "expected 5" in e for e in errors)


