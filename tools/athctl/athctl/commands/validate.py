"""LLM-judge validation: score plans / sessions against a coaching rubric.

A second Claude instance acts as an independent judge - it does not see
the conversation that produced the plan, only the plan + athlete
context. Returns a numeric score per criterion plus an overall verdict.

Use this after the agent ships a new plan to confirm quality, or as
part of a regression sweep when you change prompts / tools.
"""

from __future__ import annotations

import json
import logging
import os
import sys

import click

from athctl.common import EXIT_BACKEND_DOWN, console, emit, get_supabase, require_active_user

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Rubric
# ---------------------------------------------------------------------------

RUBRIC = {
    "progressive_overload": (
        "Does the plan show progressive overload appropriate for the phase? "
        "Volume and intensity should rise over weeks (base building) or "
        "feature targeted overreaching followed by recovery (build/peak)."
    ),
    "recovery_balance": (
        "Is recovery integrated? At least 1-2 easy or rest days per week, "
        "no two hard days back-to-back, and a deload every 3-4 weeks."
    ),
    "goal_specificity": (
        "Does the plan move the athlete towards the stated goal "
        "(event, target time, race pace)? Race-specific work in build/peak."
    ),
    "plausible_targets": (
        "Are pace / HR / power targets plausible for the athlete's current "
        "fitness and the phase? Easy paces should match aerobic effort, "
        "threshold should sit at LT, race pace only in build/peak."
    ),
    "constraint_compliance": (
        "Does the plan respect athlete constraints (training days/week, "
        "max session minutes, sport preferences, free-form notes)?"
    ),
    "session_variety": (
        "Mix of session types appropriate to the goal: easy, tempo, "
        "threshold, intervals, long, strength, cross-train. Avoid monotony."
    ),
}


JUDGE_SYSTEM_PROMPT = """\
You are an independent endurance-coaching judge evaluating a training plan
generated by another coach for a specific athlete. Score the plan honestly
against the rubric. Each criterion is scored 0-100. Be specific in feedback:
cite which session or week supports each score. Be tough but constructive -
this is regression-testing the coach, not advising the athlete.

Return ONLY a JSON object with this exact schema:

{
  "scores": {
    "<criterion_name>": {"score": int (0-100), "feedback": "..." },
    ...
  },
  "overall_score": int (weighted average, weights below),
  "verdict": "pass" | "fail" | "mixed",
  "key_issues": ["...", ...],
  "key_strengths": ["...", ...]
}

Weights for overall:
- progressive_overload 20
- recovery_balance 20
- goal_specificity 20
- plausible_targets 15
- constraint_compliance 15
- session_variety 10

Verdict: "pass" if overall >= 75, "fail" if < 60, else "mixed".
"""


def _call_judge(plan_json: dict, athlete_context: dict) -> dict:
    """Run the judge LLM call and return its JSON verdict.

    Uses anthropic SDK directly (separate API call from the main coach).
    Falls back gracefully when the SDK is unavailable.
    """
    try:
        import anthropic
    except ImportError:
        return {"error": "anthropic SDK not installed (uv add anthropic)"}

    rubric_json = json.dumps(RUBRIC, indent=2)
    user_msg = (
        "## Athlete Context\n"
        f"```json\n{json.dumps(athlete_context, indent=2, default=str)}\n```\n\n"
        "## Plan to Evaluate\n"
        f"```json\n{json.dumps(plan_json, indent=2, default=str)}\n```\n\n"
        "## Rubric\n"
        f"```json\n{rubric_json}\n```\n\n"
        "Now produce your JSON verdict."
    )

    try:
        client = anthropic.Anthropic()
        response = client.messages.create(
            model="claude-haiku-4-5-20251001",
            max_tokens=4096,
            system=JUDGE_SYSTEM_PROMPT,
            messages=[{"role": "user", "content": user_msg}],
        )
    except Exception as exc:
        return {"error": f"Judge LLM call failed: {exc}"}

    text = ""
    for block in response.content:
        if getattr(block, "type", None) == "text":
            text += getattr(block, "text", "")

    text = text.strip()
    # Strip code fences if model wrapped JSON
    if text.startswith("```"):
        text = text.split("\n", 1)[1] if "\n" in text else text
        text = text.rsplit("```", 1)[0]
    try:
        return json.loads(text)
    except json.JSONDecodeError as exc:
        return {"error": f"Could not parse judge response as JSON: {exc}", "raw": text[:2000]}


def _athlete_context(uid: str) -> dict:
    """Build a minimal athlete context dict for the judge."""
    client = get_supabase()
    profile = client.table("profiles").select("*").eq("user_id", uid).execute()
    beliefs = (
        client.table("beliefs")
        .select("text, category, confidence")
        .eq("user_id", uid)
        .eq("active", True)
        .order("confidence", desc=True)
        .limit(15)
        .execute()
    )
    return {
        "profile": profile.data[0] if profile.data else {},
        "beliefs": beliefs.data or [],
    }


