@click.group(help="LLM-judge validation against a coaching rubric.")
def validate() -> None:
    """Validate plans / sessions via an independent judge."""


@validate.command("plan", help="Validate a specific saved plan (or the active one).")
@click.option("--id", "plan_id", default=None, help="Plan id; default is the active plan.")
def validate_plan(plan_id: str | None) -> None:
    uid = require_active_user()
    client = get_supabase()

    if not plan_id:
        res = (
            client.table("plans")
            .select("id, plan_data")
            .eq("user_id", uid)
            .eq("active", True)
            .limit(1)
            .execute()
        )
        if not res.data:
            print("No active plan and no --id given.", file=sys.stderr)
            sys.exit(2)
        plan_id = res.data[0]["id"]
        plan_data = res.data[0]["plan_data"]
    else:
        res = client.table("plans").select("plan_data").eq("id", plan_id).execute()
        if not res.data:
            print(f"Plan {plan_id} not found.", file=sys.stderr)
            sys.exit(2)
        plan_data = res.data[0]["plan_data"]

    emit(f"Judging plan {plan_id}...")
    verdict = _call_judge(plan_data, _athlete_context(uid))

    if "error" in verdict:
        console.print(f"[red]Judge error:[/red] {verdict['error']}")
        sys.exit(EXIT_BACKEND_DOWN)

    overall = verdict.get("overall_score")
    v = verdict.get("verdict")
    emit(
        f"Verdict: {v} (overall {overall}/100)",
        data={"plan_id": plan_id, "verdict": verdict},
    )

    scores = verdict.get("scores", {})
    for crit, payload in scores.items():
        score = payload.get("score") if isinstance(payload, dict) else None
        feedback = payload.get("feedback") if isinstance(payload, dict) else ""
        console.print(f"  [bold]{crit}[/bold]: {score}/100 - {str(feedback)[:160]}")

    issues = verdict.get("key_issues") or []
    if issues:
        console.print("\n[red]Key issues:[/red]")
        for i in issues:
            console.print(f"  - {i}")
    strengths = verdict.get("key_strengths") or []
    if strengths:
        console.print("\n[green]Key strengths:[/green]")
        for s in strengths:
            console.print(f"  - {s}")


@validate.command("batch", help="Run the judge against N independent plan generations.")
@click.option("--runs", type=int, default=3, help="How many times to re-judge.")
@click.option("--id", "plan_id", default=None, help="Plan id; default active.")
def validate_batch(runs: int, plan_id: str | None) -> None:
    """Re-judge the same plan multiple times to see judge consistency."""
    uid = require_active_user()
    client = get_supabase()

    if not plan_id:
        res = (
            client.table("plans")
            .select("id, plan_data")
            .eq("user_id", uid)
            .eq("active", True)
            .limit(1)
            .execute()
        )
        if not res.data:
            print("No active plan and no --id given.", file=sys.stderr)
            sys.exit(2)
        plan_id = res.data[0]["id"]
        plan_data = res.data[0]["plan_data"]
    else:
        res = client.table("plans").select("plan_data").eq("id", plan_id).execute()
        plan_data = res.data[0]["plan_data"]

    ctx = _athlete_context(uid)
    scores: list[int] = []
    for i in range(max(1, runs)):
        verdict = _call_judge(plan_data, ctx)
        if "error" in verdict:
            console.print(f"[red]Run {i+1} failed:[/red] {verdict['error']}")
            continue
        s = verdict.get("overall_score")
        if isinstance(s, int):
            scores.append(s)
        console.print(f"Run {i+1}: {verdict.get('verdict')} ({s}/100)")

    if scores:
        avg = sum(scores) / len(scores)
        spread = max(scores) - min(scores)
        emit(
            f"\nMean overall: {avg:.1f}/100, spread {spread}",
            data={"plan_id": plan_id, "scores": scores, "mean": avg, "spread": spread},
        )
